"""
Parallel schedule comparison training.

Trains two different schedules simultaneously on separate GPUs.
This is a temporary utility for schedule comparison experiments.

Recommended schedules for comparison: Linear, VP, VE

Usage:
    python train_parallel_schedules.py --schedule1 linear --schedule2 vp --steps 10000

After training completes, compare the checkpoints to analyze memorization dynamics.
"""

import torch
import subprocess
import argparse
import sys
import os

# Check if we have 2 GPUs available
if torch.cuda.device_count() < 2:
    print("[ERROR] This script requires 2 GPUs. Found: {} GPU(s)".format(torch.cuda.device_count()))
    print("[INFO] Use regular train.py instead.")
    sys.exit(1)


def create_schedule_config(schedule_type: str, n_steps: int) -> str:
    """Create a temporary config file for the given schedule."""
    config_content = f"""# Temporary config for {schedule_type} schedule comparison
# Auto-generated by train_parallel_schedules.py

# Device settings - use single GPU for parallel training
use_dual_gpu: false

# Dataset settings
dataset_name: "mnist"
img_channels: 1
img_size: 32
batch_size: 128

# Training (step-based) - limited for comparison
lr: 0.0001
n_steps: {n_steps}
timesteps: 1000
log_every: 100

# Diffusion schedule configuration
schedule_type: "{schedule_type}"
# Linear schedule parameters
b0: 0.0001
bT: 0.02
# Fixed schedule parameters
beta: 0.006
# VP schedule parameters
beta_d: 19.9
beta_min: 0.1
# VE schedule parameters
sigma_min: 0.02
sigma_max: 100.0

# Paths
checkpoint_dir: "model_ckpts/schedule_comparison/{schedule_type}"
log_dir: "logs/schedule_comparison/{schedule_type}"
run_name: "mnist_{schedule_type}_steps{n_steps}"

# Normalization
center: true
normalize: false

# Checkpointing
save_initial:
  - 100
  - 250
  - 500
  - 1000
  - 2500
  - 5000
save_interval: 2500
"""
    return config_content


def run_training(schedule_type: str, gpu_id: int, n_steps: int):
    """Run training on a specific GPU."""
    config_path = f"configs/temp_{schedule_type}_{n_steps}steps.yaml"

    # Create temporary config
    with open(config_path, 'w') as f:
        f.write(create_schedule_config(schedule_type, n_steps))

    # Set environment to use specific GPU
    env = os.environ.copy()
    env['CUDA_VISIBLE_DEVICES'] = str(gpu_id)

    print(f"\n[GPU {gpu_id}] Starting {schedule_type} schedule training...")
    print(f"[GPU {gpu_id}] Config: {config_path}")
    print(f"[GPU {gpu_id}] Steps: {n_steps}")
    print(f"[GPU {gpu_id}] Output: model_ckpts/schedule_comparison/{schedule_type}/")

    # Run training
    try:
        result = subprocess.run(
            [sys.executable, "train.py", "--config", config_path],
            env=env,
            check=True
        )
        print(f"\n[GPU {gpu_id}] {schedule_type} training COMPLETED")
        return 0
    except subprocess.CalledProcessError as e:
        print(f"\n[GPU {gpu_id}] {schedule_type} training FAILED: {e}")
        return 1
    finally:
        # Clean up temp config
        if os.path.exists(config_path):
            os.remove(config_path)


def main():
    parser = argparse.ArgumentParser(description="Train two schedules in parallel")
    parser.add_argument("--schedule1", type=str, default="linear", help="First schedule type")
    parser.add_argument("--schedule2", type=str, default="vp", help="Second schedule type")
    parser.add_argument("--steps", type=int, default=10000, help="Number of training steps")
    args = parser.parse_args()

    # Validate schedule types
    valid_schedules = ["linear", "vp", "ve", "fixed"]
    if args.schedule1 not in valid_schedules:
        print(f"[ERROR] Invalid schedule1: {args.schedule1}. Valid: {valid_schedules}")
        sys.exit(1)
    if args.schedule2 not in valid_schedules:
        print(f"[ERROR] Invalid schedule2: {args.schedule2}. Valid: {valid_schedules}")
        sys.exit(1)

    print("=" * 60)
    print("PARALLEL SCHEDULE COMPARISON TRAINING")
    print("=" * 60)
    print(f"Schedule 1 (GPU 0): {args.schedule1}")
    print(f"Schedule 2 (GPU 1): {args.schedule2}")
    print(f"Training steps: {args.steps}")
    print(f"Output directories:")
    print(f"  - model_ckpts/schedule_comparison/{args.schedule1}/")
    print(f"  - model_ckpts/schedule_comparison/{args.schedule2}/")
    print("=" * 60)

    # Create output directories
    os.makedirs(f"model_ckpts/schedule_comparison/{args.schedule1}", exist_ok=True)
    os.makedirs(f"model_ckpts/schedule_comparison/{args.schedule2}", exist_ok=True)
    os.makedirs(f"logs/schedule_comparison/{args.schedule1}", exist_ok=True)
    os.makedirs(f"logs/schedule_comparison/{args.schedule2}", exist_ok=True)

    # Run both trainings in parallel
    from multiprocessing import Process

    p1 = Process(target=run_training, args=(args.schedule1, 0, args.steps))
    p2 = Process(target=run_training, args=(args.schedule2, 1, args.steps))

    p1.start()
    p2.start()

    print("\n[INFO] Both training processes started. Monitor GPU usage with nvidia-smi")
    print("[INFO] Check logs in terminal outputs above for progress")

    p1.join()
    p2.join()

    print("\n" + "=" * 60)
    print("PARALLEL TRAINING COMPLETE")
    print("=" * 60)
    print(f"\nTo compare results:")
    print(f"1. Generate samples:")
    print(f"   python sample.py model_ckpts/schedule_comparison/{args.schedule1}/mnist_{args.schedule1}_steps{args.steps}.pth")
    print(f"   python sample.py model_ckpts/schedule_comparison/{args.schedule2}/mnist_{args.schedule2}_steps{args.steps}.pth")
    print(f"\n2. Compare memorization metrics (when implemented):")
    print(f"   python evaluation/compare_memorization.py --checkpoint1 model_ckpts/schedule_comparison/{args.schedule1}/...")
    print(f"   --checkpoint2 model_ckpts/schedule_comparison/{args.schedule2}/...")


if __name__ == "__main__":
    main()
